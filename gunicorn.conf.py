# Настройки gunicorn
bind = "0.0.0.0:5000"

workers = 1        # ВАЖНО: именно ОДИН процесс — состояние игр хранится в его памяти.
                   # Если процессов будет два, игра начнёт «терять» партии.
threads = 8        # Зато потоков несколько: пока один ждёт данные от браузера,
                   # остальные спокойно отвечают — сайт не зависает.
timeout = 60       # Сколько секунд ждать, прежде чем убить воркера (было 30)
worker_tmp_dir = "/dev/shm"  # «пульс» воркеров в оперативную память, а не на диск —
                             # известная докерная настройка от ложных убийств воркеров